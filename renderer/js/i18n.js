let lang = 'en';
export function setLang(l) { lang = l === 'ru' ? 'ru' : 'en'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function t(key, vars) {
  let s = (lang === 'ru' ? RU[key] : EN[key]) || EN[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
// tiny helper for settings strings: tr('English', 'Русский')
export const tr = (en, ru) => (lang === 'ru' ? ru : en);
